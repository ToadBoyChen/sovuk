/**
 * Generates lib/worldGrid.ts: a dot grid of the whole world (Antarctica
 * cropped). "#" = land, "U" = United Kingdom, "." = sea. Run with
 * `node scripts/build-world-grid.mjs [rows]`. Plain equirectangular
 * projection, mirrored in `projectToWorld`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const ROWS = Number(process.argv[2] ?? 80);
const LAT_MAX = 80;
const LAT_MIN = -56;
const LON_MIN = -180;
const LON_MAX = 180;
const LAT0 = 0;

const read = (f) => JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/${f}`, import.meta.url)));
const landTopo = read("land-50m.json");
const land = feature(landTopo, landTopo.objects.land);
const countries = read("countries-50m.json");
const uk = feature(countries, countries.objects.countries.geometries.find((g) => g.id === "826"));

const cellDeg = (LAT_MAX - LAT_MIN) / ROWS;
const lonScale = Math.cos((LAT0 * Math.PI) / 180);
const cols = Math.round(((LON_MAX - LON_MIN) * lonScale) / cellDeg);
const lonPerCell = cellDeg / lonScale;

const offsets = [[0.5, 0.5], [0.25, 0.25], [0.75, 0.25], [0.25, 0.75], [0.75, 0.75]];
const rows = [];
for (let y = 0; y < ROWS; y++) {
  let line = "";
  for (let x = 0; x < cols; x++) {
    let landHits = 0;
    let ukHits = 0;
    for (const [ox, oy] of offsets) {
      const pt = [LON_MIN + (x + ox) * lonPerCell, LAT_MAX - (y + oy) * cellDeg];
      if (geoContains(land, pt)) landHits++;
      if (geoContains(uk, pt)) ukHits++;
    }
    // The UK is small at this scale, so any hit counts; other land needs two.
    line += ukHits >= 1 ? "U" : landHits >= 2 ? "#" : ".";
  }
  rows.push(line);
}

const out = `// Generated by scripts/build-world-grid.mjs — do not edit by hand.
// The world on a ${cols} × ${ROWS} grid: "#" land, "U" United Kingdom, "." sea.

export const worldGrid = {
  cols: ${cols},
  rows: ${ROWS},
  latMax: ${LAT_MAX},
  lonMin: ${LON_MIN},
  cellDeg: ${cellDeg},
  lonPerCell: ${lonPerCell},
  data: [
${rows.map((r) => `    "${r}",`).join("\n")}
  ],
} as const;

/** Maps a latitude/longitude to fractional grid coordinates. */
export function projectToWorld(lat: number, lon: number) {
  return {
    x: (lon - worldGrid.lonMin) / worldGrid.lonPerCell,
    y: (worldGrid.latMax - lat) / worldGrid.cellDeg,
  };
}
`;
writeFileSync(new URL("../lib/worldGrid.ts", import.meta.url), out);
const all = rows.join("");
console.log(`lib/worldGrid.ts: ${cols} × ${ROWS}, land ${all.split("#").length - 1}, UK ${all.split("U").length - 1}`);
